def joint_tex(vanilla, imgs, scale=1, k=255, iters=12, seed=0, p0_weight=160.0, exact=None,
              pal_weight=None, solo=None, lone_slots=None):
    """A multi-palette TEX whose index map serves every palette's picture.

    ESUI (like any FFNx pack) draws DIFFERENT things in different palettes of
    one sheet -- btl_win_b's slot reels only in 11, its stars only in 3..10,
    its digits in all of them -- and a TEX has one index map for all 16.
    ff7nx_ddstex.convert_group derives that map from one reference frame,
    which is right for a cycling animation and loses everything the other
    frames draw elsewhere. Here every texel is described by its colour in
    every palette at once and the 255 index slots are k-means clusters of
    those 16-palette descriptions; slot 0 stays clear in every palette.
    Palette p's colour for a slot is the mean of its members' colour in p,
    clear where most members are clear in p. Layout: vanilla's (same
    palettes, colour key and index size), widened to 256 colours as every
    converted multi-palette TEX in this build already is."""
    import numpy as np
    import ff7nx_ddstex as DT
    import tex
    t = tex.parse(vanilla)
    n_pal, cpp = t['num_palettes'], t['colors_per_palette']
    W, H = t['width'] * scale, t['height'] * scale
    vpal = np.frombuffer(t['palette'], np.uint8).reshape(n_pal, cpp, 4)
    rgb = np.zeros((n_pal, H * W, 3), np.float32)
    on = np.zeros((n_pal, H * W), bool)
    for p in range(n_pal):
        a = DT._resample_area(np.ascontiguousarray(imgs[p]), W, H)
        rgb[p] = a[:, :, :3].reshape(-1, 3)
        on[p] = a[:, :, 3].reshape(-1) >= 128
    any_on = on.any(0)
    # BUILD 628: texels in `exact` (x0, y0, x1, y1, output texels) get slots of
    # their own palette-0 colour -- the window frame's dark / light / dark
    # lines. Clustered with the rest, the bottom edge's reversed gradient was
    # averaged into one flat mid-grey (the bottom border darker than the top).
    ex = np.zeros(H * W, bool)
    ex_lab = None
    if exact is not None:
        x0, y0, x1, y1 = exact
        m2 = np.zeros((H, W), bool)
        m2[y0:y1, x0:x1] = True
        ex = m2.reshape(-1) & on[0]
        cols = np.rint(rgb[0][ex]).astype(np.int32)
        ucol, ex_lab = np.unique(cols, axis=0, return_inverse=True)
        ex_lab = ex_lab.reshape(-1)
        k -= len(ucol)
        any_on = any_on & ~ex
    # BUILD 629: pal_weight scales a palette's say in the clustering. The
    # palettes ESUI does not supply are the game's own art over the whole
    # sheet (btl_win_b 12 and 14: 207k texels each); at full weight they took
    # the slots ESUI's HP digits (7, 13) needed -- the dirty pixels around
    # "HP" and the mark in the middle of the 8.
    pw = np.ones(n_pal, np.float32) if pal_weight is None else np.asarray(pal_weight, np.float32)
    # BUILD 645: ...but only where ESUI draws something. Where no supplied
    # palette is on (btl_win_b's lower half: the field countdown timer's
    # digits, palette 12 alone) the filler palettes ARE the picture; scaled
    # down there their texels all fell within one cluster and the timer
    # came out as a purple block (trains, the reactor, the inn's hours).
    # Those texels get full weight and slots of their own (LONE_SLOTS), so
    # they cannot take the ones ESUI's art needs (the 629 problem).
    supplied = pw >= 1.0
    pwt = np.broadcast_to(pw[None, :], (H * W, n_pal)).copy()
    lone = np.zeros(H * W, bool)
    if supplied.any() and not supplied.all():
        lone = ~on[supplied].any(0)
        pwt[lone] = 1.0
    feat = np.concatenate([(rgb.transpose(1, 0, 2) * on.T[:, :, None]
                            * pwt[:, :, None]).reshape(H * W, -1),
                           on.T.astype(np.float32) * pwt
                           * np.array([p0_weight] + [160.0] * (n_pal - 1), np.float32)], 1)
    rng = np.random.default_rng(seed)

    def d2(A, C):
        # float64 + errstate: Accelerate's matmul (macOS) raises spurious
        # divide/overflow/invalid flags on float32 even for finite inputs.
        with np.errstate(all='ignore'):
            r = (A * A).sum(1)[:, None] - 2.0 * (A @ C.T) + (C * C).sum(1)[None, :]
        r = np.nan_to_num(r, nan=np.inf, posinf=np.inf, neginf=0.0)
        return np.maximum(r, 0.0)

    def kmeans(U, w, k):
        k = min(k, len(U))
        # k-means++ on a weighted sample
        sample = rng.choice(len(U), size=min(len(U), 20000), replace=False,
                            p=w / w.sum())
        S = U[sample]
        C = [S[rng.integers(len(S))]]
        dmin = d2(S, np.array(C))[:, 0]
        for _ in range(1, k):
            pr = np.where(np.isfinite(dmin), np.maximum(dmin, 0), 0.0)
            if pr.sum() <= 0:
                break
            c = S[rng.choice(len(S), p=pr / pr.sum())]
            C.append(c)
            dmin = np.minimum(dmin, d2(S, c[None, :])[:, 0])
        C = np.array(C)
        lab = np.zeros(len(U), np.int64)
        for _ in range(iters):
            for i in range(0, len(U), 8192):
                lab[i:i + 8192] = d2(U[i:i + 8192], C).argmin(1)
            for j in range(len(C)):
                m = lab == j
                if m.any():
                    C[j] = (U[m] * w[m, None]).sum(0) / w[m].sum()
        return lab, len(C)

    def cluster(sel, kk):
        X = feat[sel]
        uniq, inv, cnt = np.unique(X.astype(np.int16), axis=0,
                                   return_inverse=True, return_counts=True)
        lab, n = kmeans(uniq.astype(np.float64), cnt.astype(np.float64), kk)
        return lab[inv.reshape(-1)], n

    # BUILD 705: `solo` = (palette, (x0, y0, x1, y1) output texels, slots): a
    # rectangle only that palette ever draws (btl_win_b's timer cells,
    # palette 12). Its texels are clustered on that palette's colour alone,
    # into slots of their own: what the other palettes would show there is
    # never drawn, so it neither costs them slots nor bends their colours.
    solo_m = np.zeros(H * W, bool)
    if solo is not None:
        sp, (sx0, sy0, sx1, sy1), s_slots = solo
        m2 = np.zeros((H, W), bool)
        m2[sy0:sy1, sx0:sx1] = True
        solo_m = m2.reshape(-1) & on[sp] & ~ex
        any_on = any_on & ~solo_m
        k_all = k
        k -= s_slots
    lone_n = LONE_SLOTS if lone_slots is None else lone_slots
    if solo is not None:
        # the cells were lone texels (no supplied palette draws there): their
        # slots come out of the lone budget, the main clustering keeps its own
        lone_n = max(lone_n - s_slots, 1)
    idx = np.zeros(H * W, np.uint8)
    lone_on = any_on & lone
    if lone_on.sum() >= lone_n * 4 and lone_n < k:
        main_on = any_on & ~lone
        lab_m, n_m = cluster(main_on, k - lone_n)
        lab_l, n_l = cluster(lone_on, lone_n)
        idx[main_on] = (lab_m + 1).astype(np.uint8)
        idx[lone_on] = (lab_l + 1 + n_m).astype(np.uint8)
        nC = n_m + n_l
    else:
        lab, nC = cluster(any_on, k)
        idx[any_on] = (lab + 1).astype(np.uint8)
    C = range(nC)
    if solo_m.any():
        fs = np.concatenate([rgb[sp][solo_m], on[sp][solo_m, None] * 160.0], 1)
        uniq, inv, cnt = np.unique(fs.astype(np.int16), axis=0,
                                   return_inverse=True, return_counts=True)
        # at least its own budget, plus whatever the others left unused
        lab_s, n_s = kmeans(uniq.astype(np.float64), cnt.astype(np.float64),
                            max(s_slots, k_all - nC))
        idx[solo_m] = (lab_s[inv.reshape(-1)] + 1 + nC).astype(np.uint8)
        nC += n_s
        C = range(nC)
    if ex_lab is not None and ex.any():
        idx[ex] = (nC + 1 + ex_lab).astype(np.uint8)
        nC += int(ex_lab.max()) + 1
        C = range(nC)
    out = np.zeros((n_pal, 256, 4), np.uint8)
    for p in range(n_pal):
        nz = vpal[p][:, 3][vpal[p][:, 3] > 0]
        opaque_a = 254 if (len(nz) and (nz == 254).mean() >= 0.5) else 255
        sel = idx > 0
        lab_p = idx[sel].astype(np.int64)
        tot = np.bincount(lab_p, minlength=256).astype(np.float64)
        onp = on[p][sel]
        n_on = np.bincount(lab_p, weights=onp, minlength=256)
        for c in range(3):
            s_ = np.bincount(lab_p, weights=rgb[p][sel][:, c] * onp, minlength=256)
            out[p, :, 2 - c] = np.clip(np.rint(s_ / np.maximum(n_on, 1)), 0, 255)
        out[p, :, 3] = np.where((n_on * 2 > tot) & (tot > 0), opaque_a, 0)
        out[p, 0] = 0
    hdr = bytearray(vanilla[:tex.HEADER_LEN])
    struct.pack_into('<I', hdr, tex.O_WIDTH, W)
    struct.pack_into('<I', hdr, tex.O_HEIGHT, H)
    old_pitch = struct.unpack_from('<I', vanilla, tex.O_PITCH)[0]
    if old_pitch:
        struct.pack_into('<I', hdr, tex.O_PITCH, old_pitch * scale)
    struct.pack_into('<I', hdr, tex.O_COLORS_PER_PAL, 256)
    struct.pack_into('<I', hdr, tex.O_COLORS_PER_PAL2, 256)
    struct.pack_into('<I', hdr, tex.O_PAL_SIZE, n_pal * 256)
    if struct.unpack_from('<I', vanilla, tex.O_COLORKEY)[0] == 0:
        struct.pack_into('<I', hdr, tex.O_COLORKEY, 1)
    data = bytes(hdr) + out.tobytes() + idx.tobytes()
    chk = tex.parse(data)
    if chk is None or chk['num_palettes'] != n_pal or chk['width'] != W:
        raise ValueError('joint TEX does not parse back')
    if scale > 1:
        data = tex.mark_logical_scale(data, scale)
    err = []
    for p in range(n_pal):
        m = on[p] if solo is None or p == sp else on[p] & ~solo_m
        if m.any():
            pr = out[p][idx][:, [2, 1, 0]].astype(np.float32)
            err.append(float(np.abs(pr[m] - rgb[p][m]).mean()))
    note = ('%dx%d -> %dx%d x%d, %d palettes x 256 colours (joint, %d slots), '
            'mean colour error %.1f' % (t['width'], t['height'], W, H, scale,
                                         n_pal, len(C), float(np.mean(err)) if err else 0))
    return data, note


