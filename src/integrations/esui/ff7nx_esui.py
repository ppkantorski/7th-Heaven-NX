def esui_data():
    """BUILD 629: every byte the active ESUI folders write outside .text --
    the guest image each port was generated and verified on (esui_port's
    DATA_NEW: stock code + all of ESUI's data) -- except what the module
    carries its own way. Bytes DATA_MAIN / DATA_SHOP set are left to them
    (our Buy/Sell/Exit split and box width)."""
    mem = hext_bytes()
    if mem is None:
        return list(DATA_BATTLE)
    src = _HEXT_SRC.get(tuple(CURRENT['folders']), {})
    own = set()
    for va, old, new, _w in DATA_MAIN + DATA_SHOP:
        own.update(range(va, va + len(new)))
    lo, hi = TEXT_RANGE
    out = []
    for va in sorted(mem):
        if lo <= va < hi or va in own:
            continue
        if any(a <= va < b for a, b in DATA_SKIP_RANGES):
            continue
        if any(k in src.get(va, '') for k in DATA_SKIP_FILES):
            continue
        b = (mem[va] + DATA_DELTA.get(va, 0)) & 0xFF
        out.append((va, None, bytes([b]), 'ESUI data (active options)'
                    + (' + our tweak' if va in DATA_DELTA else '')))
    if screen_ports('battle'):
        out += [d for d in DATA_BATTLE if lo <= d[0] < hi]          # the dispatcher byte read as data
    return out


def calendar_owned(text=None):
    """Module words ff7nx_calendar wrote, if it is installed in `text`.

    The Echo-S calendar rebuilds the main menu's Time/Gil box, which is the
    same box 00-Main moves. On PC the pair is resolved by ESUI's own
    `ECHOS/MAIN/05 - ESUI Theme.txt`; here ff7nx_calendar carries that layout
    as its ESUI profile, so when it is installed those words are its. Decided
    from the module itself (its Gil-label hook is a `bl` into its cave, not
    the stock call), because the calendar fails closed and may not be there
    even when it was asked for. This pass runs after it.
    """
    try:
        import ff7nx_calendar as C
    except ImportError:
        return set()
    if text is None or len(text) < C.DATE_HOOK + 4:
        return set()
    if struct.unpack_from('<I', text, C.DATE_HOOK)[0] == C.DATE_HOOK_ORIG:
        return set()
    return C.owned_sites()


