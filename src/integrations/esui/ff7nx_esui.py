def _shift(f, d):
    k = f[0]
    if k in ('add', 'const'):
        return (k, f[1] + d)
    if k in ('affd', 'aff'):
        return f[:4] + (f[4] + d,)
    if k == 'map':
        return (k, tuple((a, b + d) for a, b in f[1]))
    raise ValueError('cannot shift a %r transform' % (k,))


