def hext_bytes():
    """{x86 va: byte} as the ACTIVE ESUI folders' HEXT leave ff7_en: 7th
    Heaven applies them in mod.xml declaration order (not the art order),
    last write wins. None when the archive cannot be read."""
    key = tuple(CURRENT['folders'])
    if key in _HEXT_MEM:
        return _HEXT_MEM[key]
    import iro
    try:
        iro.list_entries(CURRENT['mod'].path)
    except Exception:                                           # noqa: BLE001
        _HEXT_MEM[key] = None
        return None
    decl = {}
    man = getattr(CURRENT['mod'], 'manifest', None)
    try:
        man = man or iro.Manifest(CURRENT['mod'].path)
        for i, (f, _c) in enumerate(man.folders):
            decl.setdefault(f.replace('\\', '/').lower(), i)
    except Exception:                                           # noqa: BLE001
        pass
    mem, src = {}, {}
    for folder in sorted(dict.fromkeys(f.lower() for f in CURRENT['folders']),
                         key=lambda f: decl.get(f, 1 << 30)):
        for ln, d in _folder_hext(folder):
            for va, x in d.items():
                mem[va] = x
                src[va] = ln
    _HEXT_MEM[key] = mem
    _HEXT_SRC[key] = src
    return mem


def _data_from(ranges, what):
    mem = hext_bytes()
    if mem is None:
        return None
    return [(va, None, bytes([mem[va]]), what) for va in sorted(mem)
            if any(lo <= va < hi for lo, hi in ranges)]


