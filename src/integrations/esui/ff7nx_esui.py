def _with_deltas(screen, fn, port):
    if screen == 'battle' and fn == FADE_FN:
        port = _battle_fade(port)
    if screen == 'battle' and fn == LIMIT_TINT_FN:
        port = dict(port)
        sc = dict(port.get('store_const', []))
        sc.update({pc: LIMIT_TINT for pc in LIMIT_TINT_STORES})
        port['store_const'] = sorted(sc.items())
    so = STORE_OVERRIDE.get(screen, {}).get(fn)
    if so:
        port = dict(port)
        port['stores'] = {**port.get('stores', {}), **so}
    calls = CALL_HOOKS.get(screen, {}).get(fn)
    if calls:
        port = dict(port)
        port['calls'] = list(port.get('calls', [])) + list(calls)
    bd = BACKDROP.get(screen, {}).get(fn)
    if bd:
        port = dict(port)
        port['backdrop'] = list(port.get('backdrop', [])) + list(bd)
    deltas = SITE_DELTA.get(screen, {}).get(fn)
    maps = SITE_MAP.get(screen, {}).get(fn)
    if not deltas and not maps:
        return port
    port = dict(port)
    port['sites'] = dict(port['sites'])
    for site, (callee, dj) in (deltas or {}).items():
        c, tr, post = port['sites'].get(site, (callee, {}, []))
        if c != callee:
            raise ValueError('SITE_DELTA %X: the port calls %X there, not %X' % (site, c, callee))
        if -1 in tr:
            raise ValueError('SITE_DELTA %X: a split site' % site)
        tr = dict(tr)
        for j, d in dj.items():
            tr[j] = _shift(tr[j], d) if j in tr else ('add', d)
        port['sites'][site] = (c, tr, post)
    for site, (callee, mj) in (maps or {}).items():
        c, tr, post = port['sites'].get(site, (callee, {}, []))
        if c != callee:
            raise ValueError('SITE_MAP %X: the port calls %X there, not %X' % (site, c, callee))
        tr = dict(tr)
        for j, pairs in mj.items():
            f = tr.get(j, ('add', 0))
            if f[0] != 'add':
                raise ValueError('SITE_MAP %X arg %d: a %r transform' % (site, j, f[0]))
            tr[j] = ('addmap', f[1], tuple(pairs))
        port['sites'][site] = (c, tr, post)
    return port


_SCREEN_PORTS = {}


def fn_variant(fs, fe):
    """The ESUI variant of one x86 function: a hash of the bytes the active
    folders' HEXT write inside it (ff7nx_esui_ports keys its ports by it)."""
    import hashlib
    mem = hext_bytes()
    if mem is None:
        return None
    b = sorted((va, x) for va, x in mem.items() if fs <= va < fe)
    return hashlib.sha1(repr(b).encode()).hexdigest()[:10]


def screen_ports(screen, log=lambda *_: None):
    """{fn: port} for a ported screen under the ACTIVE ESUI options, or None
    (the screen stays stock: data and code). BUILD 629: every function has a
    port per ESUI variant of its code, each generated and verified for an
    option set that produces it, so the options in settings.json pick the
    layout. A variant nobody verified keeps the whole screen stock."""
    if CURRENT is None:
        return None
    key = (screen, tuple(CURRENT['folders']))
    if key in _SCREEN_PORTS:
        return _SCREEN_PORTS[key]
    try:
        import ff7nx_esui_ports as PP
    except ImportError:
        return None
    fns = PP.PORTS.get(screen)
    out = None
    if fns and hext_bytes() is not None:
        out, missing = {}, []
        for fn, variants in sorted(fns.items()):
            h = fn_variant(*PP.FN_RANGE[fn])
            if h in variants:
                out[fn] = _with_deltas(screen, fn, variants[h])
            else:
                missing.append('%X' % fn)
        if missing:
            log('! Enhanced Stock UI: %s stays stock -- these ESUI options change '
                '%s in a way no port was verified for' % (screen, ', '.join(missing)))
            out = None
        else:
            # BUILD 631: 710C50 sets the magic lists' cursor/scroll row counts
            # (ESUI: 10); the lists themselves (710DFA) are not ported yet and
            # show the game's 7 rows -- with both, the cursor ran off the
            # bottom and the scroll stopped early. Stock together or ported
            # together.
            if 0x710DFA not in fns:
                out.pop(0x710C50, None)
            # functions ESUI leaves alone but the alignment pass moves
            empty = {'words': {}, 'sites': {}, 'hooks': [], 'replace': [],
                     'skip_calls': [], 'store_const': [], 'stores': {}}
            for fn in (set(SITE_DELTA.get(screen, {})) | set(SITE_MAP.get(screen, {}))
                       | set(CALL_HOOKS.get(screen, {})) | set(BACKDROP.get(screen, {}))):
                if fn not in out:
                    out[fn] = _with_deltas(screen, fn, empty)
    _SCREEN_PORTS[key] = out
    return out


def port_words(src_main, text, log=lambda *_: None):
    """{va: (old, new, label)} for every enabled ported screen, caves in the
    dead body of x86 0x6AF19C. {} when nothing is ported or enabled."""
    try:
        import ff7nx_esui_ports as PP
    except ImportError:
        return {}
    if CURRENT is None:
        return {}
    ported = {s: screen_ports(s, log) for s in screens() if s in PP.PORTS}
    want = [s for s in screens() if ported.get(s) or (s in STORE_TWEAKS and s not in PP.PORTS)]
    if not want:
        return {}
    import nxmap
    import ff7nx_esuicave as EC
    import ff7nx_fieldbg
    m = nxmap.Main(src_main)
    why = ff7nx_fieldbg._liveness(m, EC.DEAD_X86)
    if why:
        raise ValueError('x86 0x%X is not dead in this module: %s' % (EC.DEAD_X86, why))
    lo, hi = m.extent(EC.DEAD_X86)
    at = lo + EC.DEAD_GUARD
    rw = lambda va: struct.unpack_from('<I', text, va)[0]          # noqa: E731
    out = {}
    for screen in want:
        st = STORE_TWEAKS.get(screen)
        if st:
            words, at = EC.build({'stores': st}, rw, m.x86_to_arm, at)
            out.update(words)
        for fn, port in sorted((ported.get(screen) or {}).items()):
            tw = SITE_TWEAKS.get(screen, {}).get(fn)
            if tw:
                port = dict(port)
                port['sites'] = dict(port['sites'])
                for site, (callee, tr) in tw.items():
                    port['sites'][site] = (callee, tr, [])
            words, at = EC.build(port, rw, m.x86_to_arm, at)
            for va, new in words.items():
                out[va] = new
        if ported.get(screen):
            for va, new in TWEAKS.get(screen, {}).items():
                out[va] = new
            # BUILD 645c: the Limit menu's names. ESUI moves their x with its
            # windows (HEXT 0x6DF498, the loop's `push 0xb0`), but the port
            # of 0x6DF40D was generated with no limit in the list, so the
            # loop never ran and the names kept the game's x=176 -- a column
            # right of where ESUI (and FFNx) draws them.
            if screen == 'battle' and LIMIT_NAME_FN in ported.get(screen):
                w = limit_name_word(rw(LIMIT_NAME_ARM))
                if w is not None:
                    out[LIMIT_NAME_ARM] = w
                # BUILD 684: and their row step. ESUI's 03-Battle sets the
                # loop's `imul eax,eax,0x1e` to 0x18 (HEXT 0x6DF490, "limit
                # box text spacing") to match the cursor's 0x18 (0x6CF84E,
                # which IS carried). Same blind spot: the names kept 30 px
                # rows under a 24 px cursor, drifting 6 px per row.
                w = limit_step_word(rw(LIMIT_STEP_ARM))
                if w is not None:
                    out[LIMIT_STEP_ARM] = w
        log('  %s: %d function(s) ported' % (screen, len(ported.get(screen) or {})))
    # BUILD 645e: "Transparency Strength". ESUI's Opacity folders set one byte,
    # the alpha 0x6E6C30 gives semi-transparent boxes (HEXT 0x6E6C53, stock
    # 0x80). Nothing ported it, so every choice drew at the stock 0x80.
    w = opacity_word(rw(OPACITY_ARM))
    if w is not None:
        out[OPACITY_ARM] = w
    if at > hi - 0x100:
        raise ValueError('ported screens need %d bytes of cave, the dead body has %d'
                         % (at - lo, hi - lo))
    return {va: (rw(va), new, 'ESUI port') for va, new in out.items()}


# BUILD 645c: see port_words.
LIMIT_NAME_FN = 0x6DF40D
LIMIT_NAME_HEXT = 0x6DF498          # imm32 of x86 `push 0xb0` (the name's x)
LIMIT_NAME_ARM = 0xD44E48           # mov w27, #0xb0 (the same x, ARM)
LIMIT_NAME_STOCK = 0x5280161B


# BUILD 684: see port_words.
LIMIT_STEP_HEXT = 0x6DF490          # imm8 of x86 `imul eax, eax, 0x1e`
LIMIT_STEP_ARM = 0xD44E44           # mov w26, #0x1e (the loop's multiplier)
LIMIT_STEP_STOCK = 0x321F0FFA


def limit_step_word(cur):
    """The ARM word that gives the Limit names ESUI's row step, or None."""
    mem = hext_bytes()
    if cur != LIMIT_STEP_STOCK or not mem or LIMIT_STEP_HEXT not in mem:
        return None
    step = mem[LIMIT_STEP_HEXT]
    if step >= 0x80:                # imul's imm8 is signed; never negative here
        return None
    return 0x52800000 | (step << 5) | 26            # movz w26, #step


OPACITY_HEXT = 0x6E6C53             # imm8 of the box alpha (x86 0x6E6C30)
OPACITY_ARM = 0xD8588C              # mov w8, #0x80 (the same alpha, ARM)
OPACITY_STOCK = 0x321903E8


def opacity_word(cur):
    """The ARM word that gives the boxes ESUI's alpha, or None."""
    mem = hext_bytes()
    if cur != OPACITY_STOCK or not mem or OPACITY_HEXT not in mem:
        return None
    return 0x52800000 | (mem[OPACITY_HEXT] << 5) | 8      # movz w8, #alpha


def limit_name_word(cur):
    """The ARM word that gives the Limit names ESUI's x, or None."""
    mem = hext_bytes()
    if cur != LIMIT_NAME_STOCK or not mem or LIMIT_NAME_HEXT not in mem:
        return None
    x = int.from_bytes(bytes(mem.get(LIMIT_NAME_HEXT + i, 0) for i in range(4)),
                       'little', signed=True)
    if 0 <= x < 0x10000:
        return 0x52800000 | (x << 5) | 27            # movz w27, #x
    if -0x10000 <= x < 0:
        return 0x12800000 | ((~x & 0xFFFF) << 5) | 27  # movn w27, #~x
    return None


