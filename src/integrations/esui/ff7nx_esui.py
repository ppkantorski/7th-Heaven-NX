def _find(root, *parts):
    """Case-insensitive path below root."""
    path = root
    for part in parts:
        try:
            hit = next((e for e in os.listdir(path) if e.lower() == part.lower()),
                       None)
        except OSError:
            return None
        if hit is None:
            return None
        path = os.path.join(path, hit)
    return path


