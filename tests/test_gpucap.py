def test_full_viewport_and_scissor_match_the_target(tmp_path, monkeypatch):
    import arm64emu
    monkeypatch.delenv(C.GPUCAP_ENV, raising=False)
    monkeypatch.delenv(C.SCALE_ENV, raising=False)
    out = _texscaled(tmp_path)
    assert C.apply_all(out, log=lambda *_: None) == 0
    img = nxmap.Main(str(out)).img
    code = {va: _w(img, va) for va in range(0x10D72F4, 0x10D7318, 4)}
    got = []
    mem = arm64emu.Mem()
    cpu = arm64emu.Cpu(mem, native={
        0x11320E0: lambda c: got.append(('scissor', c.x[2])),
        0x11320F0: lambda c: got.append(('viewport', c.x[2]))})
    rect = 0x100000
    mem.setu(rect + 0x3C, 160, 4)
    mem.setu(rect + 0x40, 240, 4)
    cpu.x[20], cpu.x[24] = rect, 0x200000
    assert cpu.run(0x10D72F4, code) == 0x10D7318
    assert got == [('scissor', 640 | 960 << 32), ('viewport', 640 | 960 << 32)]


def test_memory_per_capture():
    """What the header promises, as numbers (RGBA8, target + copy)."""
    def mb(w, h, k):
        return (w * h + (w * k) * (h * k)) * 4
    assert mb(1280, 1920, 4) == 167116800    # stock, k = 4: the pause
    assert mb(160, 240, 4) == 2611200        # authored (build 320)
    assert mb(640, 960, 1) == 4915200        # FULL, scale 4
