def _w(img, va):
    return struct.unpack_from('<I', img, va)[0]


def test_the_two_stock_words_are_what_the_module_claims(img):
    assert _w(img, C.ALLOC_SITE) == C.ALLOC_STOCK
    assert _w(img, C.VIEW_SITE) == C.VIEW_STOCK
    assert C.verify(img) == []
    assert C.read_state(img) == 'GPU capture target = scaled rect (stock)'


def test_the_stock_words_are_rebuilt_from_the_encoders_not_transcribed(img):
    """Both are generated by the same two functions that generate the patched
    words, at the fb_tex offset -- so the encoders are proven against the real
    binary before they are trusted at the tex_format offset."""
    assert C._ldp32(2, 3, 20, C.FB_OFF) == _w(img, C.ALLOC_SITE)
    assert C._ldur64(22, 20, C.FB_OFF) == _w(img, C.VIEW_SITE)


def test_every_anchor_around_the_path(img):
    for va, want in sorted(C.ANCHORS.items()):
        got = _w(img, va)
        assert got == want, '+0x%X is %08X, expected %08X' % (va, got, want)


def test_the_patch_only_changes_the_offset(img):
    """Same instruction class, same registers, same base -- only the structure
    member it reads moves from fb_tex to tex_format."""
    for va, stock in ((C.ALLOC_SITE, C.ALLOC_STOCK),
                      (C.VIEW_SITE, C.VIEW_STOCK)):
        patched = C.words_for(True)[va]
        if va == C.ALLOC_SITE:
            assert (patched & 0xFFC07FFF) == (stock & 0xFFC07FFF)
            assert ((patched >> 15) & 0x7F) * 4 == C.TEX_OFF
            assert ((stock >> 15) & 0x7F) * 4 == C.FB_OFF
        else:
            assert (patched & 0xFFE003FF) == (stock & 0xFFE003FF)
            assert ((patched >> 12) & 0x1FF) == C.TEX_OFF
            assert ((stock >> 12) & 0x1FF) == C.FB_OFF


def test_the_source_region_does_not_come_from_the_target(img):
    """The whole argument. Path B's UVs are built at +0x10D7478 from fb_tex.x/y
    and fb_tex.w/h against the SURFACE's own size, so resizing the target is a
    downscale of the same region rather than a crop of it."""
    assert _w(img, 0x10D7478) == 0x2942A688      # ldp w8,  w9,  [x20, #0x14]
    assert _w(img, 0x10D747C) == 0x2943AE8A      # ldp w10, w11, [x20, #0x1c]
    # and those reads are NOT the ones this module changes
    assert 0x10D7478 not in C.words_for(True)
    assert 0x10D747C not in C.words_for(True)


def test_tex_format_is_where_the_module_says_it_is(img):
    """+0x3C/+0x40 really are tex_format.width/height: the same store pair in
    make_framebuffer_tex writes them, next to the fb_tex pair this replaces."""
    assert _w(img, 0x10DBC90) == 0x2907DF58      # stp w24, w23, [x26, #0x3c]
    assert C.TEX_OFF == 0x3C and C.FB_OFF == 0x1C
    # adjacent 32-bit fields, so one 64-bit ldur packs (w | h << 32) either way
    assert C.TEX_OFF + 4 == 0x40


def test_the_in_battle_path_is_not_touched(img):
    """Every battle effect object sets field_0 = 1 and takes the CPU readback
    at +0x10D70B8. Neither patched site is on that path, and the selector that
    separates them is asserted intact."""
    assert _w(img, 0x10D70B0) == 0x7100051F      # cmp w8, #1
    for va in C.words_for(True, 2):
        # Path B begins at +0x10D7240; +0x4940 is its creator, called from
        # nowhere else (test_the_creator_has_one_caller)
        assert va >= 0x10D7240 or 0x4940 <= va < 0x4A08, hex(va)


def test_the_env_switch(monkeypatch):
    monkeypatch.delenv(C.GPUCAP_ENV, raising=False)
    assert C.enabled() is True
    for v in ('0', 'off', 'stock', 'no'):
        monkeypatch.setenv(C.GPUCAP_ENV, v)
        assert C.enabled() is False
    monkeypatch.setenv(C.GPUCAP_ENV, '1')
    assert C.enabled() is True
    assert C.mode() == C.FULL
    monkeypatch.setenv(C.GPUCAP_ENV, 'authored')
    assert C.mode() == C.AUTHORED and C.enabled() is True
    monkeypatch.delenv(C.GPUCAP_ENV)
    assert C.mode() == C.FULL                    # BUILD 735's default
    monkeypatch.delenv(C.SCALE_ENV, raising=False)
    assert C.scale() == 4
    for v, want in (('2', 2), ('8', 8), ('3', 4), ('x', 4), ('16', 4)):
        monkeypatch.setenv(C.SCALE_ENV, v)
        assert C.scale() == want, v


def test_apply_is_idempotent_and_reverts_byte_exactly(tmp_path):
    out = tmp_path / 'main_gpucap'
    shutil.copy(MAIN, out)
    assert C.apply_all(out, log=lambda *_: None) == 0
    got = nxmap.Main(str(out)).img
    assert C.verify(got) == []
    # the dump has no ff7nx_texscale, so FULL falls back to the authored size
    assert C.installed(got) == (C.AUTHORED, 1)
    assert C.read_state(got) == 'GPU capture target = authored size'
    assert C.apply_all(out, log=lambda *_: None) == 0
    assert C.apply_all(out, revert=True, log=lambda *_: None) == 0
    assert out.read_bytes() == open(MAIN, 'rb').read()


def test_it_writes_those_two_words_and_nothing_else(tmp_path):
    out = tmp_path / 'main_scope'
    shutil.copy(MAIN, out)
    before = nxmap.Main(str(out)).img
    assert C.apply_all(out, log=lambda *_: None) == 0
    after = nxmap.Main(str(out)).img
    diff = {i for i in range(0, len(before), 4)
            if before[i:i + 4] != after[i:i + 4]}
    assert diff == {C.ALLOC_SITE, C.VIEW_SITE}, [hex(x) for x in sorted(diff)]
    for va, want in sorted(C.ANCHORS.items()):
        assert _w(after, va) == want, hex(va)


def test_it_refuses_when_the_path_has_moved(img):
    for va in list(C.ANCHORS) + [C.ALLOC_SITE, C.VIEW_SITE]:
        bad = bytearray(img)
        struct.pack_into('<I', bad, va, 0xD503201F)          # nop
        assert C.verify(bad) != [], hex(va)


def test_a_mixed_state_is_refused(img):
    bad = bytearray(img)
    struct.pack_into('<I', bad, C.ALLOC_SITE, C.words_for(True)[C.ALLOC_SITE])
    assert C.installed(bad) is None
    assert C.verify(bad) != []


def test_the_swirl_target_stops_scaling_with_the_surface():
    """What it is for, as numbers. The swirl's rect is 320k x 480k; its
    authored size is 160 x 240 whatever k is."""
    for k in (1, 2, 4):
        scaled = 4 * (320 * k) * (480 * k) * 4
        authored = 4 * 160 * 240 * 4
        assert authored == 614400
        if k > 1:
            assert scaled > authored
    assert 4 * 1280 * 1920 * 4 == 39321600       # k = 4, stock


