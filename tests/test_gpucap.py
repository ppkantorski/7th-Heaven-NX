def _texscaled(tmp_path):
    """The dump with ff7nx_texscale applied, as the build has it when this
    pass runs (7th_heaven_nx.py: apply_texscale before apply_fbcapture)."""
    import ff7nx_texscale
    out = tmp_path / 'main_texscale'
