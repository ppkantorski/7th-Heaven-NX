import os as _nx_os, sys as _nx_sys  # BUILD 755: find src/ and put its modules on sys.path
_nx_root = _nx_os.path.dirname(_nx_os.path.abspath(__file__))
while not _nx_os.path.isfile(_nx_os.path.join(_nx_root, '7th_heaven_nx.py')) and _nx_root != _nx_os.path.dirname(_nx_root):
    _nx_root = _nx_os.path.dirname(_nx_root)
_nx_sys.path.insert(0, _nx_os.path.join(_nx_root, 'src'))
import nxpaths  # noqa: E402
nxpaths.install(tools=True)
import hashlib, os, pprint, sys, tempfile
sys.path.insert(0, os.getcwd())
import build, iro, exe_patch

OLD = sys.argv[1]          # the verified release (.iro or folder)
NEW = sys.argv[2]          # the newer release
OUT = sys.argv[3]

def load(p):
    m = build.Mod(p, tempfile.mkdtemp()); m._load_manifest(); return m

def hexts(p):
    out = {}
    for n in iro.list_entries(p):
        ln = n.replace('\\', '/').lower()
        if '/hext/' in ln and ln.endswith(('.txt', '.hext')):
            raw = iro.read_one(p, n)
            d = {}
            for va, b in exe_patch.parse_hext(raw.decode('utf-8', 'replace')):
                for k, x in enumerate(bytes(b)):
                    d[va + k] = x
            out[ln] = (hashlib.sha1(raw).hexdigest(), d)
    return out

mo, mn = load(OLD), load(NEW)
xml_new = hashlib.sha1(iro.read_one(NEW, 'mod.xml')).hexdigest()
ho, hn = hexts(OLD), hexts(NEW)
hext = {}
for ln in sorted(set(ho) & set(hn)):
    (so, do), (sn, dn) = ho[ln], hn[ln]
    if do == dn:
        continue
    hext[ln] = {'new_sha1': sn,
                'drop': sorted(k for k in dn if k not in do),
                'set': {k: v for k, v in sorted(do.items()) if dn.get(k) != v}}
removed = {ln: dict(sorted(ho[ln][1].items())) for ln in sorted(set(ho) - set(hn))}
added = sorted(set(hn) - set(ho))
profile = {
    'release': mn.manifest.version, 'pinned_to': mo.manifest.version,
    'folders': [f for f, _c in mo.manifest.folders],
    'hext': hext, 'removed': removed, 'added': added,
}
src = ('"""GENERATED by tools/esui/compat_gen.py -- do not edit.\n\n'
       'Enhanced Stock UI releases newer than the one the ESUI ports were\n'
       'verified on, pinned back to that layout: keyed by the sha1 of the\n'
       'newer release\'s mod.xml. See ff7nx_esui.compat()."""\n\n'
       'PROFILES = ' + pprint.pformat({xml_new: profile}, width=100, compact=True) + '\n')
open(OUT, 'w').write(src)
print('release', mn.manifest.version, '->', mo.manifest.version, 'hext files', len(hext),
      'removed', list(removed), 'added', added, 'folders', len(profile['folders']))
