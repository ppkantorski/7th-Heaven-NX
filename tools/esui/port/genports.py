import os as _nx_os, sys as _nx_sys  # BUILD 755: find src/ and put its modules on sys.path
_nx_root = _nx_os.path.dirname(_nx_os.path.abspath(__file__))
while not _nx_os.path.isfile(_nx_os.path.join(_nx_root, '7th_heaven_nx.py')) and _nx_root != _nx_os.path.dirname(_nx_root):
    _nx_root = _nx_os.path.dirname(_nx_root)
_nx_sys.path.insert(0, _nx_os.path.join(_nx_root, 'src'))
import nxpaths  # noqa: E402
nxpaths.install(tools=True)
import sys, os, struct, pprint
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import esui_port as P, fns
SCREENS = {}
for arg in sys.argv[1:]:
    name, lst = arg.split('=')
    SCREENS[name] = [int(x, 16) for x in lst.split(',')]
out = {}
for screen, fl in SCREENS.items():
    ports = {}
    for fn in fl:
        cfg = P.cfg_for(fn)
        pokes = [None] + P.party_pokes() + cfg.get('pokes', []) + ([] if cfg.get('no_random') else P.random_pokes(fn, n=12, extra=cfg.get('poke_extra', ()))[1:])
        pairs, tgt, st = P.sample(fn, cfg, seeds=range(2), argsets=cfg.get('argsets', P.ARGSETS[:4]), pokes=pokes)
        sites, bad, stores = P.fit_cfg(cfg, pairs, tgt)
        words = {}
        for va, new in cfg.get('arm_struct', {}).items():
            words[va] = (struct.unpack_from('<I', P.M.img, va)[0], new)
        posts = cfg.get('post', {})
        ports[fn] = {
            'words': words,
            'sites': {s: (c, {j: tuple(f) for j, f in tr.items()}, [tuple(p) for p in posts.get(s, [])])
                      for s, (c, tr) in sites.items()},
            'hooks': [(s, [tuple(o) for o in ops]) for s, ops in cfg.get('hooks', [])],
            'replace': [(s, list(w)) for s, w in cfg.get('replace', [])],
            'skip_calls': list(cfg.get('skip_calls', [])),
            'store_const': list(cfg.get('store_const', [])),
            'stores': {w: tuple(f) for w, f in sorted(stores.items())},
        }
        if bad: raise SystemExit('%x: unfitted %s' % (fn, bad))
        print('%s %x: %d words, %d sites, bad %s' % (screen, fn, len(words), len(sites), {hex(k): [j for j, _ in v] for k, v in bad.items()}))
        sys.stdout.flush()
    out[screen] = ports
dest = 'ff7nx_esui_ports.py'
old = {}
if os.path.exists(dest):
    ns = {}
    exec(open(dest).read(), ns)
    old = ns['PORTS']
old.update(out)
with open(dest, 'w') as f:
    f.write('"""GENERATED by tools/esui/port/genports.py from configs verified in the\n'
            'ARM emulator (esui_port.verify2: x86 with ESUI vs the edited ARM, call by\n'
            'call and every memory write). Do not edit by hand. See ff7nx_esuicave."""\n\n')
    f.write('PORTS = ' + pprint.pformat(old, width=110, compact=True) + '\n')
print('wrote', dest, {k: len(v) for k, v in old.items()})
