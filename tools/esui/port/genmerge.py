import os as _nx_os, sys as _nx_sys  # BUILD 755: find src/ and put its modules on sys.path
_nx_root = _nx_os.path.dirname(_nx_os.path.abspath(__file__))
while not _nx_os.path.isfile(_nx_os.path.join(_nx_root, '7th_heaven_nx.py')) and _nx_root != _nx_os.path.dirname(_nx_root):
    _nx_root = _nx_os.path.dirname(_nx_root)
_nx_sys.path.insert(0, _nx_os.path.join(_nx_root, 'src'))
import nxpaths  # noqa: E402
nxpaths.install(tools=True)
import sys, os, pprint
SC = os.path.dirname(os.path.abspath(__file__))
dest = 'ff7nx_esui_ports.py'
ns = {}; exec(open(dest).read(), ns); old = ns['PORTS']
for arg in sys.argv[1:]:
    name, lst = arg.split('=')
    old[name] = {int(x, 16): eval(open(os.path.join(SC, 'ports_out', '%s.py' % x)).read()) for x in lst.split(',')}
with open(dest, 'w') as f:
    f.write('"""GENERATED by tools/esui/port/genports.py from configs verified in the\n'
            'ARM emulator (esui_port.verify2: x86 with ESUI vs the edited ARM, call by\n'
            'call and every memory write). Do not edit by hand. See ff7nx_esuicave."""\n\n')
    f.write('PORTS = ' + pprint.pformat(old, width=110, compact=True) + '\n')
    import json as _j, sys as _s
    _s.path.insert(0, '.')
    import iro as _iro
    fol = _j.load(open(os.environ.get('ESUI_FOLDERS', os.path.join(SC, 'folders_now.json'))))
    names = {(e if isinstance(e, str) else e[0]).replace('\\', '/').lower()
             for e in _iro.list_entries('mods/Enhanced Stock UI-rel2.iro')}
    hf = sorted(x for x in fol if any(n.startswith(x.lower().rstrip('/') + '/hext/') for n in names))
    f.write('\n# the ESUI folders (with exe patches) these ports were generated and verified for\n')
    f.write('PORTS_FOLDERS = ' + pprint.pformat(hf, width=110) + '\n')
print('wrote', dest, {k: len(v) for k, v in old.items()})
