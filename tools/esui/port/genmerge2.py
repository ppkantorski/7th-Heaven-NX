import os as _nx_os, sys as _nx_sys  # BUILD 755: find src/ and put its modules on sys.path
_nx_root = _nx_os.path.dirname(_nx_os.path.abspath(__file__))
while not _nx_os.path.isfile(_nx_os.path.join(_nx_root, '7th_heaven_nx.py')) and _nx_root != _nx_os.path.dirname(_nx_root):
    _nx_root = _nx_os.path.dirname(_nx_root)
_nx_sys.path.insert(0, _nx_os.path.join(_nx_root, 'src'))
import nxpaths  # noqa: E402
nxpaths.install(tools=True)
import sys, os, re, json, ast, pprint
SC = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, '.')
import nxmap
M = nxmap.Main('dump/exefs/main')
SCREEN = {
    'battle': [0x41b300, 0x41c0bb, 0x5bb756, 0x5bcd42, 0x5bcf9d, 0x5bd050, 0x6ce8b3, 0x6cf5c5, 0x6d0af9, 0x6d1cc0,
               0x6d797c, 0x6d7dfa, 0x6d84c4, 0x6d982c, 0x6d9ad5, 0x6d9faf, 0x6da23c, 0x6dac2d, 0x6daef0, 0x6dc976,
               0x6dd041, 0x6de3db, 0x6debfe, 0x6df40d, 0x6df9ba, 0x6dfc65, 0x6e06c9, 0x6e09bb, 0x6e0d28, 0x6e1308,
               0x6e1f64, 0x6e2170, 0x6e3135, 0x6e384f, 0x6e4b3c],
    'load': [0x6fedb0, 0x720775, 0x7212fb],
    'shop': [0x719e90, 0x71a6e6, 0x71aaa3, 0x71e415, 0x71ee01, 0x71fa7d],
}
# accepted by hand (BUILD 627): 41B300 cannot be emulated (two constants checked);
# 720775 differs only by our own save-slot TWEAKS
HAND = {0x41b300, 0x720775}
var = json.load(open(os.path.join(SC, 'variants.json')))
skip = set(int(x, 16) for x in os.environ.get('SKIP', '').split(',') if x)
ports, rng, report = {}, {}, []
for fnx, vl in sorted(var.items()):
    fn = int(fnx, 16)
    if fn in skip:
        continue
    scr = next((k for k, v in SCREEN.items() if fn in v), 'menus')
    ok = {}
    for v in vl:
        h = v['hash']
        base = os.path.join(SC, 'ports_var', '%x_%s' % (fn, h))
        if not os.path.exists(base + '.py') or not os.path.exists(base + '.txt'):
            report.append((fn, h, 'NOT RUN')); continue
        txt = open(base + '.txt').read()
        m = re.findall(r'fn %x: (\d+)/(\d+) runs differ' % fn, txt)
        good = m and int(m[-1][0]) == 0
        if not good and fn not in HAND:
            report.append((fn, h, 'DIFFERS %s' % (str(m[-1]) if m else '?'))); continue
        ok[h] = ast.literal_eval(open(base + '.py').read())
    if ok:
        ports.setdefault(scr, {})[fn] = ok
        rng[fn] = M.containing(fn)
    print('%x %-6s %d/%d variants' % (fn, scr, len(ok), len(vl)))
dest = 'ff7nx_esui_ports.py'
with open(dest, 'w') as f:
    f.write('"""GENERATED by tools/esui/port/genmerge2.py from configs verified in the\n'
            'ARM emulator (esui_port.verify2: x86 with ESUI vs the edited ARM, call by\n'
            'call and every memory write), one port per ESUI variant of each function:\n'
            'the variant is a hash of the bytes the active option folders\' HEXT write in\n'
            'it (ff7nx_esui.fn_variant). Do not edit by hand. See ff7nx_esuicave."""\n\n')
    f.write('PORTS = ' + pprint.pformat(ports, width=110, compact=True) + '\n\n')
    f.write('FN_RANGE = ' + pprint.pformat({k: tuple(v) for k, v in rng.items()}, width=110, compact=True) + '\n')
print('wrote', dest, {k: len(v) for k, v in ports.items()})
json.dump([(hex(a), b, c) for a, b, c in report], open(os.path.join(SC, 'merge_report.json'), 'w'), indent=0)
print(len(report), 'variants left out')
